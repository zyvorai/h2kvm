function loadLocale(): Locale {
  try {
    const raw = localStorage.getItem('h2kweb-locale');
    if (raw === 'en' || raw === 'de' || raw === 'fr' || raw === 'es' || raw === 'ja') return raw;
  } catch {
    /* SSR / vitest */
  }
  return 'en';
}

let currentLocale: Locale = loadLocale();

export function t(key: string): string {
  return translations[currentLocale]?.[key] || translations.en[key] || key;
}

export function setLocale(locale: Locale) {
  currentLocale = locale;
  localStorage.setItem('h2kweb-locale', locale);
  window.location.reload();
}

export function getLocale(): Locale {
  return currentLocale;
}

export function getAvailableLocales(): { code: Locale; label: string }[] {
  return [
    { code: 'en', label: 'English' },
    { code: 'de', label: 'Deutsch' },
    { code: 'fr', label: 'Français' },
    { code: 'es', label: 'Español' },
    { code: 'ja', label: '日本語' },
  ];
}
